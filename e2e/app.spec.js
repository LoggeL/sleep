import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const base=process.env.BASE_URL||'http://localhost:5187';
test.use({timezoneId:'Europe/Berlin',locale:'de-DE',permissions:['clipboard-read','clipboard-write']});
test('all modes, local preferences, share and calendar work',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/#v=1&mode=wake&date=2026-11-03&time=07%3A00&buffer=15&cycle=90');
 await expect(page.locator('.option')).toHaveCount(4);
 await expect(page.locator('.option').first()).toContainText('21:45');
 await expect(page.locator('#timezone')).toContainText('Europe/Berlin');
 await page.getByRole('button',{name:'Ins Bett um',exact:true}).click();
 await page.locator('#date').fill('2026-11-02');await page.locator('#time').fill('23:00');
 await page.getByRole('button',{name:'Meine Nacht planen'}).click();
 await expect(page.locator('#results-title')).toContainText('aufzuwachen');
 await expect(page.locator('.option').first()).toContainText('03:45');
 await page.locator('[data-cycles="6"]').click();
 await expect(page.locator('#wake-time')).toHaveText('08:15');
 const download=page.waitForEvent('download');await page.locator('#calendar').click();
 const d=await download;const stream=await d.createReadStream();let ics='';for await(const chunk of stream)ics+=chunk;
 expect(ics).toContain('DTSTART:20261102T220000Z');expect(ics).toContain('DTEND:20261103T071500Z');
 await page.locator('#share').click();const url=await page.evaluate(()=>navigator.clipboard.readText());expect(url).toContain('mode=bed');
 await page.goto(url);await expect(page.locator('#time')).toHaveValue('23:00');
 await page.getByRole('button',{name:'Jetzt schlafen',exact:true}).click();
 await expect(page.locator('#time-fields')).toBeHidden();await expect(page.locator('.option')).toHaveCount(4);
 await page.locator('[data-cycles="6"]').focus();await page.waitForTimeout(1300);
 await expect(page.locator('[data-cycles="6"]')).toBeFocused();
 expect(errors).toEqual([]);
});
test('mobile responsive, legacy link, privacy, keyboard and accessibility',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto(base+'/#sleep=36');
 await expect(page.locator('#time')).toHaveValue('00:36');
 await expect(page.locator('[data-mode=bed]')).toHaveAttribute('aria-pressed','true');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('[data-cycles="6"]').focus();await page.keyboard.press('Enter');
 await expect(page.locator('[data-cycles="6"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('#privacy').click();await expect(page.locator('dialog')).toBeVisible();
 await page.locator('#clear').click();expect(await page.evaluate(()=>localStorage.getItem('nachtplan:preferences'))).toBeNull();
 await page.keyboard.press('Escape');await expect(page.locator('dialog')).toBeHidden();
 const results=await new AxeBuilder({page}).analyze();expect(results.violations).toEqual([]);
 await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1100});await page.goto(base);
 await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
});
